-- Licensing ledger for Wi-Fi Auto-Login (Cloudflare D1 / SQLite).
-- Apply once:   wrangler d1 execute wifi-licenses --remote --file=schema.sql
-- Later changes go in numbered, additive files under migrations/ (never edit this file in place
-- once it has been applied to the live database).

-- One row per app installation that has ever paid, been revoked, or been unlocked by the seller.
-- An install ID with no row is simply "trial" (the server never needs to know about trial users).
CREATE TABLE IF NOT EXISTS devices (
  install_id  TEXT PRIMARY KEY,                       -- random UUID v4 generated by the app
  status      TEXT NOT NULL DEFAULT 'trial'
              CHECK (status IN ('trial', 'paid', 'revoked')),
  paid_at     TEXT,                                   -- ISO-8601 UTC
  payment_id  TEXT                                    -- Razorpay payment that unlocked this install
);

-- One row per Razorpay payment. payment_id is the idempotency anchor: a redelivered webhook
-- can never create a second row, so it can never unlock twice.
CREATE TABLE IF NOT EXISTS payments (
  payment_id   TEXT PRIMARY KEY,                      -- pay_xxx
  link_ref     TEXT,                                  -- reference_id of the payment link ('manual' if seller-created)
  install_id   TEXT,                                  -- install currently bound to this payment (NULL for a refund tombstone)
  phone        TEXT,                                  -- buyer's number, normalised to 10 digits, for self-service restore
  amount       INTEGER,                               -- paise
  event_id     TEXT UNIQUE,                           -- x-razorpay-event-id of the delivery that created the row
  rebinds_used INTEGER NOT NULL DEFAULT 0,            -- self-service moves to a new install (budget is per payment)
  refunded     INTEGER NOT NULL DEFAULT 0,            -- 1 = fully refunded: never unlocks, never rebinds
  refunded_at  TEXT,
  created_at   TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_payments_phone ON payments (phone);
CREATE INDEX IF NOT EXISTS idx_payments_install ON payments (install_id);

-- Payment links we created. Razorpay requires reference_id to be unique per link, so it is a
-- per-link nonce here and this table maps it back to the install that asked for the link.
CREATE TABLE IF NOT EXISTS payment_links (
  reference_id TEXT PRIMARY KEY,
  link_id      TEXT,                                  -- plink_xxx
  install_id   TEXT NOT NULL,
  short_url    TEXT NOT NULL,
  amount       INTEGER NOT NULL,                      -- paise
  expires_at   INTEGER NOT NULL,                      -- unix seconds
  created_at   TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_links_install ON payment_links (install_id, expires_at);

-- Fixed-window counters used to rate-limit /pay, /restore and /admin/reset.
CREATE TABLE IF NOT EXISTS rate_limits (
  bucket     TEXT PRIMARY KEY,
  count      INTEGER NOT NULL,
  expires_at INTEGER NOT NULL                         -- unix seconds; old rows are purged opportunistically
);
